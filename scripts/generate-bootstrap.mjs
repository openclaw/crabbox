#!/usr/bin/env node

import { readFile, writeFile } from "node:fs/promises";
import { realpathSync } from "node:fs";
import { spawnSync } from "node:child_process";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import { parseStrictJSON } from "./generate-linux-readiness.mjs";

const scriptPath = fileURLToPath(import.meta.url);
export const repoRoot = resolve(dirname(scriptPath), "..");
const sourceDirectory = "recipes/bootstrap/v1";
const provenance = "// Code generated by scripts/generate-bootstrap.mjs from recipes/bootstrap/v1; DO NOT EDIT.\n";
// These fields describe the portable catalog, not provider selection or fallback policy.
export const imageFields = {
  Selector: "selector", AWSName: "awsName", AWSArm64Name: "awsArm64Name", AWSLabel: "awsLabel",
  AzureImage: "azureImage", AzureArm64Image: "azureArm64Image", GCPImage: "gcpImage",
  HetznerImage: "hetznerImage", LinodeImage: "linodeImage", DockerImage: "dockerImage",
  ContainerName: "containerName", AppleVMImage: "appleVMImage", AppleVMSHA256: "appleVMSHA256",
};
const artifactFields = {
  tightVNCMSI: ["URL", "SHA256"], gitForWindowsSetup: ["URL", "SHA256"],
  openSSHWin64Zip: ["URL", "SHA256"], ubuntuWSLRootFS: ["URL", "SHA256"],
  wslTruffleHog: ["Version", "AMD64SHA256"],
  defaultTailscale: ["Version", "AMD64SHA256", "ARM64SHA256", "KeyringSHA256"],
  defaultCodeServer: ["Version", "AMD64SHA256", "ARM64SHA256"],
  googleLinuxSigningKey: ["Fingerprint"],
};
/** @typedef {"ps-string" | "ps-strings" | "sh-string" | "sh-strings"} ParameterType */
/** @typedef {{name: string, file: string, parameters: Record<string, ParameterType>, source: string}} Fragment */
const parameterTypes = new Set(["ps-string", "ps-strings", "sh-string", "sh-strings"]);
const identifier = /^[a-z][A-Za-z0-9]*$/u;

function exactKeys(value, keys, label) {
  if (!value || typeof value !== "object" || Array.isArray(value) ||
      Object.keys(value).sort().join(",") !== [...keys].sort().join(",")) {
    throw new Error(`${label} must contain exactly: ${keys.join(", ")}`);
  }
}
function string(value, label, allowEmpty = false) {
  if (typeof value !== "string" || (!allowEmpty && !value) || /[\u0000-\u001f\u007f]/u.test(value)) {
    throw new Error(`${label} must be a ${allowEmpty ? "" : "nonempty "}single-line string`);
  }
}
function httpsURL(value, label) {
  string(value, label);
  const url = new URL(value);
  if (url.protocol !== "https:" || url.username || url.password || url.hash || url.search) {
    throw new Error(`${label} must be a credential-free HTTPS URL without query or fragment`);
  }
}
function sha256(value, label) {
  if (!/^[a-f0-9]{64}$/u.test(value)) throw new Error(`${label} must be a lowercase SHA-256 digest`);
}
export function validateArtifacts(document) {
  exactKeys(document, ["schema", "artifacts"], "artifacts");
  if (document.schema !== "crabbox-bootstrap-artifacts/v1") throw new Error("unsupported artifact schema");
  exactKeys(document.artifacts, Object.keys(artifactFields), "artifacts.artifacts");
  const constants = {};
  for (const [name, fields] of Object.entries(artifactFields)) {
    const artifact = document.artifacts[name];
    exactKeys(artifact, fields, name);
    for (const field of fields) {
      const value = artifact[field];
      const key = name + field;
      string(value, key);
      if (field === "URL") httpsURL(value, key);
      else if (field.endsWith("SHA256")) sha256(value, key);
      else if (field === "Version" && !/^\d+\.\d+\.\d+$/u.test(value)) throw new Error(`invalid version: ${key}`);
      else if (field === "Fingerprint" && !/^[A-F0-9]{40}$/u.test(value)) throw new Error(`invalid fingerprint: ${key}`);
      constants[key] = value;
    }
  }
  constants.wslTruffleHogVersionPattern = `(^|[[:space:]])${constants.wslTruffleHogVersion.replaceAll(".", "[.]")}($|[[:space:]])`;
  return constants;
}
export function validateCatalog(document) {
  exactKeys(document, ["schema", "default", "supported", "aliases", "images"], "catalog");
  if (document.schema !== "crabbox-os-catalog/v1") throw new Error("unsupported catalog schema");
  if (!Array.isArray(document.images) || !document.images.length) throw new Error("catalog needs images");
  const selectors = new Set();
  for (const image of document.images) {
    exactKeys(image, Object.keys(imageFields), "image");
    for (const [key, value] of Object.entries(image)) string(value, key, key === "LinodeImage");
    if (!/^[a-z][a-z0-9]*:[0-9]+\.[0-9]+$/u.test(image.Selector) || selectors.has(image.Selector)) {
      throw new Error(`invalid or duplicate selector: ${image.Selector}`);
    }
    selectors.add(image.Selector);
    if (!/^[a-z0-9][a-z0-9.:-]*\/[a-z0-9][a-z0-9._/-]*@sha256:[a-f0-9]{64}$/u.test(image.ContainerName)) {
      throw new Error("ContainerName must be a fully qualified, tagless OCI SHA-256 reference");
    }
    httpsURL(image.AppleVMImage, "AppleVMImage");
    sha256(image.AppleVMSHA256, "AppleVMSHA256");
  }
  if (!selectors.has(document.default)) throw new Error("default OS must exist");
  if (!Array.isArray(document.supported) || document.supported.length !== selectors.size ||
      new Set(document.supported).size !== selectors.size || document.supported.some((x) => !selectors.has(x))) {
    throw new Error("supported OS list must contain every selector exactly once");
  }
  if (!document.aliases || typeof document.aliases !== "object" || Array.isArray(document.aliases)) throw new Error("aliases must be an object");
  for (const [alias, selector] of Object.entries(document.aliases)) {
    if (!/^[a-z][a-z0-9:.]*$/u.test(alias) || selectors.has(alias) || !selectors.has(selector)) throw new Error(`invalid alias: ${alias}`);
  }
  return document;
}
export const psQuote = (value) => `'${value.replaceAll("'", "''")}'`;
// Bash ANSI-C escapes keep embedded READY here-documents safe for multiline values.
export const shellQuote = (value) => `'${value.replaceAll("'", "'\\''").replaceAll("\n", () => "'$'\\n''").replaceAll("\r", () => "'$'\\r''")}'`;

export function fragmentTokens(fragment, constants) {
  const used = new Set();
  const tokens = [];
  let offset = 0;
  for (const match of fragment.source.matchAll(/\{\{([^{}]+)\}\}/gu)) {
    tokens.push({ literal: fragment.source.slice(offset, match.index) });
    const token = match[1];
    if (Object.hasOwn(fragment.parameters, token)) {
      used.add(token);
      tokens.push({ parameter: token, type: fragment.parameters[token] });
    } else {
      const [quoting, name, extra] = token.split(":");
      if (extra || !["ps", "sh"].includes(quoting) || !Object.hasOwn(constants, name)) throw new Error(`${fragment.name}: unknown placeholder ${token}`);
      tokens.push({ literal: (quoting === "ps" ? psQuote : shellQuote)(constants[name]) });
    }
    offset = match.index + match[0].length;
  }
  tokens.push({ literal: fragment.source.slice(offset) });
  if (tokens.some((token) => token.literal?.includes("{{") || token.literal?.includes("}}"))) throw new Error(`${fragment.name}: malformed placeholder`);
  if (Object.keys(fragment.parameters).some((name) => !used.has(name))) throw new Error(`${fragment.name}: unused parameter`);
  const merged = [];
  for (const token of tokens) {
    const previous = merged.at(-1);
    if (token.literal !== undefined && previous?.literal !== undefined) previous.literal += token.literal;
    else if (token.literal !== "") merged.push(token);
  }
  return merged.length ? merged : [{ literal: "" }];
}
export async function loadSources(root = repoRoot) {
  const directory = resolve(root, sourceDirectory);
  const json = async (name) => parseStrictJSON(await readFile(resolve(directory, name), "utf8"), name);
  const constants = validateArtifacts(await json("artifacts.json"));
  const catalog = validateCatalog(await json("os-catalog.json"));
  const manifest = await json("fragments.json");
  exactKeys(manifest, ["schema", "fragments"], "fragments");
  if (manifest.schema !== "crabbox-bootstrap-fragments/v1" || !Array.isArray(manifest.fragments) || !manifest.fragments.length) throw new Error("invalid fragment manifest");
  const names = new Set();
  const fragments = [];
  for (const fragment of manifest.fragments) {
    exactKeys(fragment, ["name", "file", "parameters"], "fragment");
    if (!identifier.test(fragment.name) || names.has(fragment.name)) throw new Error("invalid or duplicate fragment name");
    names.add(fragment.name);
    if (!new RegExp(`^${fragment.name}\\.(sh|ps1)$`, "u").test(fragment.file)) throw new Error("invalid fragment file");
    if (!fragment.parameters || typeof fragment.parameters !== "object" || Array.isArray(fragment.parameters)) throw new Error("invalid parameters");
    for (const [name, type] of Object.entries(fragment.parameters)) {
      if (!identifier.test(name) || !parameterTypes.has(type)) throw new Error(`invalid parameter ${name}`);
    }
    const source = await readFile(resolve(directory, fragment.file), "utf8");
    if (!source || source.includes("\r") || source.includes("\0")) throw new Error(`${fragment.name}: use nonempty LF text without NUL`);
    const loaded = { ...fragment, source };
    fragmentTokens(loaded, constants);
    fragments.push(loaded);
  }
  return { constants, catalog, fragments };
}
function gofmt(source) {
  const result = spawnSync("gofmt", [], { input: source, encoding: "utf8" });
  if (result.status !== 0) throw new Error(result.stderr || String(result.error));
  return result.stdout;
}
const functionName = (name) => "shared" + name[0].toUpperCase() + name.slice(1);
const quoteFunction = (type) => type.startsWith("ps") ? "bootstrapPSQuote" : "bootstrapShellQuote";
function fragmentFunction(fragment, constants, language) {
  const go = language === "go";
  const params = Object.entries(fragment.parameters).map(([name, type]) => {
    const array = type.endsWith("strings");
    return go ? `${name} ${array ? "[]string" : "string"}` : `${name}: ${array ? "readonly string[]" : "string"}`;
  }).join(", ");
  const expressions = fragmentTokens(fragment, constants).map((token) => {
    if (token.literal !== undefined) return JSON.stringify(token.literal);
    const quote = quoteFunction(token.type);
    if (!token.type.endsWith("strings")) return `${quote}(${token.parameter})`;
    const words = go ? `bootstrapQuoteWords(${token.parameter}, ${quote}, ${JSON.stringify(token.type.startsWith("ps") ? ", " : " ")})` : `${token.parameter}.map(${quote}).join(${JSON.stringify(token.type.startsWith("ps") ? ", " : " ")})`;
    return token.type.startsWith("ps") ? `("@(" + ${words} + ")")` : words;
  });
  return go ? `func ${functionName(fragment.name)}(${params}) string {\nreturn ${expressions.join(" + ")}\n}\n` : `// prettier-ignore\nexport function ${functionName(fragment.name)}(${params}): string {\n  return ${expressions.join(" + ")};\n}\n`;
}
export function generateSources({ constants, catalog, fragments }) {
  let go = provenance + '\npackage cli\n\nimport "strings"\n\n';
  let ts = provenance + "\n";
  for (const [name, value] of Object.entries(constants)) {
    go += `const ${name} = ${JSON.stringify(value)}\n`;
    ts += `// prettier-ignore\nexport const ${name} = ${JSON.stringify(value)};\n`;
  }
  go += `
func bootstrapPSQuote(value string) string { return "'" + strings.ReplaceAll(value, "'", "''") + "'" }
func bootstrapShellQuote(value string) string { return "'" + strings.NewReplacer("'", "'\\\\''", "\\n", "'$'\\\\n''", "\\r", "'$'\\\\r''").Replace(value) + "'" }
func bootstrapQuoteWords(values []string, quote func(string) string, separator string) string {
  quoted := make([]string, len(values))
  for i, value := range values { quoted[i] = quote(value) }
  return strings.Join(quoted, separator)
}
`;
  ts += `
function bootstrapPSQuote(value: string): string {
  return "'" + value.replaceAll("'", "''") + "'";
}

// prettier-ignore
function bootstrapShellQuote(value: string): string {
  return (
    "'" +
    value.replaceAll("'", "'\\\\''").replaceAll("\\n", () => "'$'\\\\n''").replaceAll("\\r", () => "'$'\\\\r''") +
    "'"
  );
}
`;
  for (const fragment of fragments) {
    go += "\n" + fragmentFunction(fragment, constants, "go");
    ts += "\n" + fragmentFunction(fragment, constants, "ts");
  }
  let catalogGo = provenance + '\npackage cli\n\n';
  let catalogTS = provenance + '\n';
  for (const [name, value] of Object.entries({ defaultOSImage: catalog.default, supportedOSImages: catalog.supported.join(", ") })) {
    catalogGo += `const ${name} = ${JSON.stringify(value)}\n`;
    catalogTS += `export const ${name} = ${JSON.stringify(value)};\n`;
  }
  catalogGo += '\ntype osImageSpec struct {\n' + Object.keys(imageFields).map((f) => `${f} string`).join('\n') + '\n}\n';
  catalogTS += '\nexport interface OSImageSpec {\n' + Object.values(imageFields).map((f) => `  ${f}: string;`).join('\n') + '\n}\n';
  catalogGo += '\nvar osImageAliases = map[string]string{\n' + Object.entries(catalog.aliases).map(([k,v]) => `${JSON.stringify(k)}: ${JSON.stringify(v)},`).join('\n') + '\n}\n';
  catalogTS += '\n// prettier-ignore\nexport const osImageAliases: Readonly<Record<string, string>> = ' + JSON.stringify(catalog.aliases) + ';\n';
  catalogGo += '\nvar osImageSpecs = map[string]osImageSpec{\n' + catalog.images.map((image) => `${JSON.stringify(image.Selector)}: {\n` + Object.entries(image).map(([k,v]) => `${k}: ${JSON.stringify(v)},`).join('\n') + '\n},').join('\n') + '\n}\n';
  catalogTS += '\n// prettier-ignore\nexport const osImageSpecs: Readonly<Record<string, OSImageSpec>> = ' + JSON.stringify(Object.fromEntries(catalog.images.map((image) => [image.Selector, Object.fromEntries(Object.entries(image).map(([key,value]) => [imageFields[key], value]))]))) + ';\n';
  return new Map([
    ["internal/cli/bootstrap_generated.go", gofmt(go)],
    ["worker/src/bootstrap.generated.ts", ts],
    ["internal/cli/os_image.go", gofmt(catalogGo)],
    ["worker/src/os-image.generated.ts", catalogTS],
  ]);
}
export async function main(args = process.argv.slice(2), root = repoRoot) {
  if (args.some((arg) => arg !== "--check")) throw new Error("usage: generate-bootstrap.mjs [--check]");
  const outputs = generateSources(await loadSources(root));
  for (const [path, content] of outputs) {
    let existing;
    try { existing = await readFile(resolve(root, path), "utf8"); }
    catch (error) { if (error.code !== "ENOENT") throw error; }
    if (existing === content) continue;
    if (args.includes("--check")) throw new Error(`${path} is stale; run node scripts/generate-bootstrap.mjs`);
    await writeFile(resolve(root, path), content);
  }
}
if (process.argv[1] && realpathSync(process.argv[1]) === realpathSync(scriptPath)) await main();
