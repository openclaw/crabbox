const sample = "package cli\ntype PilotConfig struct {\n" +
	" Name string `config:\"name\" env:\"PILOT_NAME\" flag:\"pilot-name\" sources:\"user,repo,env,flag\" help:\"Name\" default:\"test\"`\n" +
	" Count int `config:\"count\" env:\"PILOT_COUNT\" flag:\"pilot-count\" sources:\"user,repo,env,flag\" help:\"Count\" default:\"7\" nonnegative:\"true\"`\n" +
	" CPUs float64 `config:\"cpus\" env:\"PILOT_CPUS\" flag:\"pilot-cpus\" sources:\"user,repo,env,flag\" help:\"CPUs\" default:\"0.5\"`\n" +
	" Enabled bool `config:\"enabled\" env:\"PILOT_ENABLED\" flag:\"pilot-enabled\" sources:\"user,repo,env,flag\" help:\"Enabled\" default:\"true\"`\n" +
	" Ports []string `config:\"ports\" env:\"PILOT_PORTS\" flag:\"pilot-ports\" sources:\"user,repo,env,flag\" help:\"Ports\"`\n}"

func TestGenerateDeterministicTypedBindings(t *testing.T) {
	s, err := parseSchema([]byte(sample), "PilotConfig", "pilot")
	if err != nil {
		t.Fatal(err)
	}
	first, err := generate(s, "pilot.go")
	if err != nil {
		t.Fatal(err)
	}
	typecheckGenerated(t, sample, first)
	second, err := generate(s, "pilot.go")
	if err != nil {
		t.Fatal(err)
	}
	if !bytes.Equal(first, second) {
		t.Fatal("nondeterministic output")
	}
	for _, want := range []string{
		"Code generated by scripts/configgen from pilot.go; DO NOT EDIT.",
		"const PilotConfigDefaultCount int = 7",
		"const PilotConfigDefaultCPUs float64 = 0.5",
		"const PilotConfigDefaultEnabled bool = true",
		"func (cfg *PilotConfig) applyFile(file *filePilotConfig) error",
		"if file.Enabled != nil", "cfg.Ports = normalizeList(*file.Ports)",
		`getenvFloat("PILOT_CPUS", cfg.CPUs)`,
		`getenvNonNegativeInt("PILOT_COUNT", cfg.Count)`,
		`getenvBool("PILOT_ENABLED")`,
		`if value := os.Getenv("PILOT_PORTS"); value != ""`,
		`fs.String("pilot-ports", strings.Join(defaults.Ports, ","), "Ports")`,
		`if flagWasSet(fs, "pilot-enabled")`,
	} {
		if !strings.Contains(string(first), want) {
			t.Fatalf("missing generated binding %q", want)
		}
	}
}

