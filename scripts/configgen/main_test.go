func TestCheckMissingFreshAndStaleOutput(t *testing.T) {
	dir := t.TempDir()
	source := filepath.Join(dir, "pilot.go")
	output := filepath.Join(dir, "generated.go")
	if err := os.WriteFile(source, []byte(sample), 0600); err != nil {
		t.Fatal(err)
	}
	if err := run(source, output, "PilotConfig", "pilot", true); err == nil {
		t.Fatal("missing output accepted")
	}
	if _, err := os.Stat(output); !os.IsNotExist(err) {
		t.Fatal("check created missing output")
	}
	if err := run(source, output, "PilotConfig", "pilot", false); err != nil {
		t.Fatal(err)
	}
	if err := run(source, output, "PilotConfig", "pilot", true); err != nil {
		t.Fatal(err)
	}
	original, err := os.ReadFile(output)
	if err != nil {
		t.Fatal(err)
	}
	if err := os.WriteFile(source, []byte(strings.Replace(sample, `default:"7"`, `default:"8"`, 1)), 0600); err != nil {
		t.Fatal(err)
	}
	if err := run(source, output, "PilotConfig", "pilot", true); err == nil {
		t.Fatal("stale output accepted")
	}
	current, err := os.ReadFile(output)
	if err != nil {
		t.Fatal(err)
	}
	if !bytes.Equal(original, current) {
		t.Fatal("check changed output")
	}
}

